                // none | table | trusted_header
                'provider' => 'none',
                'trusted_header' => 'CF-IPCountry',
            ],
            'paths' => [
                'storage' => SIGNALPOST_ROOT . '/storage',
            ],
        ];
    }

    public static function load(string $root): self
    {
        $path = getenv('SIGNALPOST_CONFIG') ?: $root . '/config/config.php';
        $user = [];
        if (is_file($path)) {
            $loaded = require $path;
            if (is_array($loaded)) {
                $user = $loaded;
            }
        }
        return self::fromArray($user);
    }

    public static function fromArray(array $user): self
    {
        return new self(self::merge(self::defaults(), $user));
    }

    public function isConfigured(): bool
    {
        return $this->get('db.name') !== '' && preg_match('/^[0-9a-f]{64}$/', (string) $this->get('app.key')) === 1;
    }

    public function get(string $key, mixed $default = null): mixed
    {
        $node = $this->values;
        foreach (explode('.', $key) as $part) {
            if (!is_array($node) || !array_key_exists($part, $node)) {
                return $default;
            }
            $node = $node[$part];
        }
        return $node;
    }

    public function int(string $key): int
    {
        return (int) $this->get($key, 0);
    }

    public function all(): array
    {
        return $this->values;
    }

    /** Binary application key used for HMACs. */
    public function appKey(): string
    {
        $hex = (string) $this->get('app.key');
        if (preg_match('/^[0-9a-f]{64}$/', $hex) !== 1) {
            throw new \RuntimeException('Application key is missing or invalid.');
        }
        return hex2bin($hex);
    }

    private static function merge(array $base, array $over): array
    {
        foreach ($over as $k => $v) {
            if (is_array($v) && isset($base[$k]) && is_array($base[$k]) && !array_is_list($base[$k])) {
                $base[$k] = self::merge($base[$k], $v);
            } else {
                $base[$k] = $v;
            }
        }
        return $base;
    }
}
