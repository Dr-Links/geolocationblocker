<?php

declare(strict_types=1);

namespace Signalpost\Core;

/**
 * Immutable configuration with dotted-key access.
 *
 * Values come from config/config.php (never committed) merged over safe
 * defaults. The path can be overridden with the SIGNALPOST_CONFIG environment
 * variable so the file can live outside the web-accessible tree.
 */
final class Config
{
    private array $values;

    private function __construct(array $values)
    {
        $this->values = $values;
    }

    public static function defaults(): array
    {
        return [
            'app' => [
                'name' => 'Signalpost',
                'url' => 'http://localhost:8080',
                'env' => 'production',
                'debug' => false,
                // 64 hex chars (32 random bytes). Generated by the installer.
                'key' => '',
            ],
            'db' => [
                'host' => 'localhost',
                'port' => 3306,
                'socket' => '',
                'name' => '',
                'user' => '',
                'password' => '',
                'charset' => 'utf8mb4',
            ],
            'security' => [
                // Exact IPs or CIDR ranges of reverse proxies whose forwarding headers are trusted.
                'trusted_proxies' => [],
                'force_https' => true,
                'session_cookie' => 'sp_session',
                'session_idle_minutes' => 120,
                'session_absolute_hours' => 168,
                'login_max_attempts' => 5,
                'login_window_minutes' => 15,
                'password_min_length' => 10,
            ],
            'mail' => [
                // "mail" uses PHP mail(); "file" writes .eml files to storage/mail (development only).
                'transport' => 'mail',
                'from' => 'no-reply@example.com',
                'from_name' => 'Signalpost',
            ],
            'polling' => [
                'widget_active_ms' => 4000,
                'widget_idle_ms' => 15000,
                'widget_hidden_ms' => 30000,
                'dashboard_ms' => 5000,
                'max_backoff_ms' => 60000,
            ],
            'limits' => [
                'max_request_bytes' => 65536,
                'message_max_chars' => 4000,
