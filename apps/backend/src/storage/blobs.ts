import { randomBytes, randomUUID } from 'node:crypto';
import { mkdir, readFile, rename, rm, writeFile } from 'node:fs/promises';
import { dirname, join, resolve } from 'node:path';
import { credentialKey } from '../admin/mfa.js';
import type { Config } from '../lib/config.js';
import { decryptBytes, encryptBytes, sha256 } from '../lib/crypto.js';
import type { Tx } from '../lib/db.js';

/** Where encrypted blobs live. Local disk today; an S3-compatible store can implement the same interface. */
export interface BlobStore {
  put(key: string, data: Buffer): Promise<void>;
  get(key: string): Promise<Buffer>;
  delete(key: string): Promise<void>;
}

export class LocalBlobStore implements BlobStore {
  private readonly root: string;
  constructor(dir: string) {
    this.root = resolve(dir);
  }
  private path(key: string) {
    // Keys are generated by us (u/<uuid>/<uuid>); refuse anything else so no path can escape the root.
    if (!/^u\/[0-9a-f-]{36}\/[0-9a-f-]{36}$/.test(key)) throw new Error('invalid blob key');
    return join(this.root, key);
  }
  async put(key: string, data: Buffer) {
    const file = this.path(key);
    await mkdir(dirname(file), { recursive: true, mode: 0o700 });
    const tmp = `${file}.${randomBytes(6).toString('hex')}.tmp`;
    await writeFile(tmp, data, { mode: 0o600 });
    await rename(tmp, file); // atomic: readers never see a half-written file
  }
  get(key: string) {
    return readFile(this.path(key));
  }
  async delete(key: string) {
    await rm(this.path(key), { force: true });
  }
}

let defaultStore: BlobStore | null = null;
export function blobStore(cfg: Config): BlobStore {
  defaultStore ??= new LocalBlobStore(cfg.blobDir);
  return defaultStore;
}

/** The user's data key (created on first use), unwrapped with the key that lives outside the database. */
async function userKey(c: Tx, cfg: Config, userId: string): Promise<Buffer> {
  const wrapKey = credentialKey(cfg);
  const load = () => c.query<{ wrapped_dek: Buffer }>(`SELECT wrapped_dek FROM user_keys WHERE user_id = $1`, [userId]);
  let { rows } = await load();
  if (!rows[0]) {
    const dek = randomBytes(32);
    await c.query(`INSERT INTO user_keys (user_id, wrapped_dek) VALUES ($1, $2) ON CONFLICT (user_id) DO NOTHING`,
      [userId, encryptBytes(wrapKey, dek, `dek:${userId}`)]);
    ({ rows } = await load());
  }
  return decryptBytes(wrapKey, rows[0]!.wrapped_dek, `dek:${userId}`);
}

/**
 * Stores content for a user, encrypted with that user's key. Identical content of the same user is
 * stored once (never shared between users, which would reveal that someone else has the same file).
 */
export async function putBlob(c: Tx, cfg: Config, userId: string, data: Buffer): Promise<{ id: string; created: boolean }> {
  const hash = sha256(data);
  const existing = await c.query<{ id: string }>(`SELECT id FROM blobs WHERE sha256 = $1`, [hash]);
  if (existing.rows[0]) return { id: existing.rows[0].id, created: false };
  const id = randomUUID();
  const key = `u/${userId}/${id}`;
  const dek = await userKey(c, cfg, userId);
  await blobStore(cfg).put(key, encryptBytes(dek, data, `blob:${id}`));
  const r = await c.query<{ id: string }>(
    `INSERT INTO blobs (id, user_id, sha256, size_bytes, storage_key) VALUES ($1, $2, $3, $4, $5)
     ON CONFLICT (user_id, sha256) DO NOTHING RETURNING id`, [id, userId, hash, data.length, key]);
  if (!r.rows[0]) {
    // Another request stored the same content at the same moment: keep theirs.
    await blobStore(cfg).delete(key);
    const again = await c.query<{ id: string }>(`SELECT id FROM blobs WHERE sha256 = $1`, [hash]);
    return { id: again.rows[0]!.id, created: false };
  }
  return { id, created: true };
}

export async function readBlob(c: Tx, cfg: Config, userId: string, blobId: string): Promise<Buffer> {
  const { rows } = await c.query<{ storage_key: string }>(`SELECT storage_key FROM blobs WHERE id = $1`, [blobId]);
  if (!rows[0]) throw new Error('blob not found');
  const dek = await userKey(c, cfg, userId);
  return decryptBytes(dek, await blobStore(cfg).get(rows[0].storage_key), `blob:${blobId}`);
}
